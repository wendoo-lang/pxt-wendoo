/*
 * Writes docs.g.ts: every page under docs/content/en/tiles/,
 * docs/content/en/types/ and docs/content/en/accessors/, packed into
 * `arcadeBaseDocs`, the lookup the arcade base pack's docs attachment reads
 * its registrations' docs from. Each `<key>.md` page is carried verbatim,
 * keyed by `<key>`, every page of the three directories in key order: a tile
 * page's key is its tile's name and a type page's its type's name, an output
 * page's is `output.<name>` under tiles/, and an accessor page's is
 * `accessor.<field>` under accessors/. Two pages with one key fail the run.
 * Run it after any page changes: `npm run gen:docs` in
 * makecode/extensions/arcade-base.
 *
 * Usage: node gen-docs.js
 */
const fs = require("fs");
const path = require("path");

/** Directory holding the locale's page directories. */
const CONTENT_DIR = path.join(__dirname, "docs", "content", "en");

/** Page directories under {@link CONTENT_DIR}: the tile and output pages, the type pages, then the accessor pages. */
const PAGE_DIRS = ["tiles", "types", "accessors"];

/** The generated STS module. */
const OUTPUT_FILE = path.join(__dirname, "docs.g.ts");

/** Extension of a page file; the file's name without it is the page's key. */
const PAGE_EXTENSION = ".md";

/**
 * Every page of every page directory as `{ name, file, markdown }`: `name`
 * its key, `file` its path under the content directory, `markdown` its text;
 * ordered by key, code unit by code unit. Throws when two pages share a key.
 */
function readPages() {
  const pages = [];
  for (const dir of PAGE_DIRS) {
    const pagesDir = path.join(CONTENT_DIR, dir);
    for (const file of fs.readdirSync(pagesDir).filter((entry) => entry.endsWith(PAGE_EXTENSION))) {
      pages.push({
        name: file.slice(0, -PAGE_EXTENSION.length),
        file: path.join(dir, file),
        markdown: fs.readFileSync(path.join(pagesDir, file), "utf8"),
      });
    }
  }
  pages.sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
  for (let i = 1; i < pages.length; i++) {
    if (pages[i].name === pages[i - 1].name) {
      throw new Error(`gen-docs: ${pages[i - 1].file} and ${pages[i].file} both have the key ${pages[i].name}`);
    }
  }
  return pages;
}

/**
 * The STS expression of `markdown`: one string literal per line, each
 * keeping its line's newline, joined by `+` and indented by `indent` after
 * the first.
 */
function markdownExpression(markdown, indent) {
  const lines = markdown.split(/(?<=\n)/);
  return lines.map((line) => JSON.stringify(line)).join(` +\n${indent}`);
}

/** The text of docs.g.ts for `pages`. */
function render(pages) {
  const out = [
    "// Generated by makecode/extensions/arcade-base/gen-docs.js from docs/content/en/{tiles,types,accessors}/*.md -- do not edit.",
    "// Regenerate after a page changes: npm run gen:docs in makecode/extensions/arcade-base.",
    "",
    "namespace wendoo {",
    "    /**",
    "     * The markdown page the arcade base pack's docs content holds under the",
    '     * key `name`, or `""` when it holds none.',
    "     */",
    "    //% hidden",
    "    export function arcadeBaseDocs(name: string): string {",
  ];
  for (const page of pages) {
    out.push(`        if (name === ${JSON.stringify(page.name)}) {`);
    out.push(`            return ${markdownExpression(page.markdown, "                ")};`);
    out.push("        }");
  }
  out.push('        return "";', "    }", "}", "");
  return out.join("\n");
}

fs.writeFileSync(OUTPUT_FILE, render(readPages()));
process.stdout.write(`gen-docs: wrote ${path.relative(process.cwd(), OUTPUT_FILE)}\n`);
